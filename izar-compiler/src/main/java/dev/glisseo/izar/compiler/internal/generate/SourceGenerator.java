/**
 * Renders an operation's {@link ObjectSelection} tree into Java source text.
 *
 * <p>Every generated record is a direct sibling inside the operation class rather than lexically
 * nested inside the record that selected it: simpler to render, and {@code
 * dev.glisseo.izar.compiler.internal.selection.SelectionAnalyzer} already guarantees every generated type
 * name is unique across the whole operation. Output is a pure function of its inputs, so identical
 * selections always produce byte-identical source.
 *
 * <p>A {@link PolymorphicSelection} renders as a sealed interface plus one sibling record per
 * branch (including the {@code Unrecognized} catch-all): each branch is an ordinary {@link
 * ObjectSelection}, so the same per-type decode/record rendering used for plain object selections
 * covers it too, with an added {@code implements} clause. Every generated {@code decodeX} method
 * takes {@code DecodingPolicy} as a second parameter and passes it on to every nested {@code
 * decodeX} call it makes, even one with no enum or polymorphic field of its own, since any nested
 * call might eventually reach one.
 */
public final class SourceGenerator {

    private SourceGenerator() {}

    /**
     * Renders a leaf-only fragment's {@link FragmentInterface} as its own top-level file: unlike
     * every other generated type, it is not a sibling inside an operation class, since it is meant
     * to be {@code implements}ed by records across many operation classes in the same package. See
     * {@code dev.glisseo.izar.compiler.internal.selection.FragmentInterfaceAnalyzer} for which fragments
     * qualify.
     */
    public static String generateFragmentInterface(String packageName, FragmentInterface fragmentInterface) {
        StringBuilder out = new StringBuilder();
        out.append("package ").append(packageName).append(";\n\n");
        out.append("import java.util.List;\n");
        out.append("import org.jspecify.annotations.NullMarked;\n");
        out.append("import org.jspecify.annotations.Nullable;\n");
        out.append('\n');
        out.append("/** Generated by Izar from fragment '")
                .append(fragmentInterface.javaTypeName())
                .append("'. Do not edit. */\n");
        out.append("@NullMarked\n");
        out.append("public interface ").append(fragmentInterface.javaTypeName()).append(" {\n\n");
        List<FieldSelection> fields = fragmentInterface.fields();
        for (int i = 0; i < fields.size(); i++) {
            out.append("    ").append(fieldTypeAndName(fields.get(i))).append("();\n");
            out.append(i < fields.size() - 1 ? "\n" : "");
        }
        out.append("}\n");
        return out.toString();
    }

    public static String generate(
            String packageName,
            String className,
            String operationName,
            String documentText,
            String operationId,
            GraphQlOperationKind operationKind,
            ObjectSelection root,
            List<OutputEnumType> outputEnumTypes,
            VariableAnalyzer.Result variables) {
        Flattened flattened = flatten(root);
        Map<String, String> implementsInterfaceByTypeName = implementsInterfaceByTypeName(flattened.polymorphicSelections());
        boolean hasVariables = !variables.variables().isEmpty();

        StringBuilder out = new StringBuilder();
        out.append("package ").append(packageName).append(";\n\n");
        out.append("import dev.glisseo.izar.operation.DecodingPolicy;\n");
        out.append("import dev.glisseo.izar.operation.GraphQlDecoding;\n");
        out.append("import dev.glisseo.izar.operation.GraphQlEncoding;\n");
        out.append("import dev.glisseo.izar.operation.GraphQlOperation;\n");
        out.append("import dev.glisseo.izar.operation.GraphQlOperationKind;\n");
        out.append("import dev.glisseo.izar.operation.ScalarCodec;\n");
        out.append("import java.util.Collections;\n");
        out.append("import java.util.LinkedHashMap;\n");
        out.append("import java.util.List;\n");
        out.append("import java.util.Map;\n");
        out.append("import org.jspecify.annotations.NullMarked;\n");
        out.append("import org.jspecify.annotations.Nullable;\n");
        out.append('\n');
        out.append("/** Generated by Izar from operation '").append(operationName).append("'. Do not edit. */\n");
        out.append("@NullMarked\n");
        out.append("public final class ")
                .append(className)
                .append(" implements GraphQlOperation<")
                .append(className)
                .append(".Data> {\n\n");

        out.append("    public static final String OPERATION_NAME = ")
                .append(JavaLiterals.quote(operationName))
                .append(";\n\n");
        out.append("    public static final String DOCUMENT = ")
                .append(JavaLiterals.quote(documentText))
                .append(";\n\n");
        out.append("    public static final String OPERATION_ID = ")
                .append(JavaLiterals.quote(operationId))
                .append(";\n\n");
        out.append("    public static final GraphQlOperationKind OPERATION_KIND = GraphQlOperationKind.")
                .append(operationKind.name())
                .append(";\n\n");

        List<CustomScalarType> customScalars = collectCustomScalars(flattened.objectSelections(), variables);
        appendScalarCodecFields(out, customScalars);

        if (hasVariables) {
            InputSourceGenerator.appendOperationVariableMembers(out, className, variables.variables());
        }

        out.append("    @Override\n    public String operationName() {\n        return OPERATION_NAME;\n    }\n\n");
        out.append("    @Override\n    public String document() {\n        return DOCUMENT;\n    }\n\n");
        out.append("    @Override\n    public String operationId() {\n        return OPERATION_ID;\n    }\n\n");
        out.append("    @Override\n    public GraphQlOperationKind operationKind() {\n        return OPERATION_KIND;\n    }\n\n");
        if (hasVariables) {
            out.append(
                    "    @Override\n    public Map<String, Object> variables() {\n        return this.variables;\n    }\n\n");
        } else {
            out.append(
                    "    @Override\n    public Map<String, Object> variables() {\n        return Map.of();\n    }\n\n");
        }

        out.append("    @Override\n    public Data decode(@Nullable Object data, DecodingPolicy policy) {\n        return decode")
                .append(root.javaTypeName())
                .append("(GraphQlDecoding.asMap(data), policy);\n    }\n\n");

        for (ObjectSelection type : flattened.objectSelections()) {
            appendDecodeMethod(out, type);
        }
        for (PolymorphicSelection polymorphic : flattened.polymorphicSelections()) {
            appendPolymorphicDecodeMethod(out, polymorphic);
        }
        for (ObjectSelection type : flattened.objectSelections()) {
            appendRecord(out, type, implementsInterfaceByTypeName.get(type.javaTypeName()));
        }
        for (PolymorphicSelection polymorphic : flattened.polymorphicSelections()) {
            appendPolymorphicInterface(out, polymorphic);
        }
        for (OutputEnumType enumType : outputEnumTypes) {
            appendOutputEnumType(out, enumType);
        }
        for (InputEnumType enumType : variables.enumTypes()) {
            InputSourceGenerator.appendEnumType(out, enumType);
        }
        for (InputObjectType inputObjectType : variables.inputObjectTypes()) {
            InputSourceGenerator.appendInputObjectType(out, inputObjectType);
        }

        out.append("}\n");
        return out.toString();
    }

    /**
     * @param objectSelections every plain object type reachable from the root, including every
     *     {@link PolymorphicSelection} branch and its {@code Unrecognized} catch-all (each is
     *     itself an ordinary {@link ObjectSelection} once built)
     * @param polymorphicSelections every interface/union-typed field's own sealed-interface
     *     container, rendered separately from {@code objectSelections} since it has no record of
     *     its own, only a decode dispatch method and a {@code permits} clause
     */
    private record Flattened(List<ObjectSelection> objectSelections, List<PolymorphicSelection> polymorphicSelections) {}

    /** Breadth-first, so a type's declaration always follows every type that references it. */
    private static Flattened flatten(ObjectSelection root) {
        List<ObjectSelection> objectSelections = new ArrayList<>();
        List<PolymorphicSelection> polymorphicSelections = new ArrayList<>();
        Deque<ObjectSelection> queue = new ArrayDeque<>();
        queue.add(root);
        while (!queue.isEmpty()) {
            ObjectSelection current = queue.removeFirst();
            objectSelections.add(current);
            for (FieldSelection field : current.fields()) {
                enqueueNestedSelections(field.shape(), queue, polymorphicSelections);
            }
        }
        return new Flattened(objectSelections, polymorphicSelections);
    }

    /**
     * Descends through any list nesting to find the object or polymorphic selection(s) a field's
     * shape reaches. A polymorphic selection's branches (including its {@code Unrecognized}
     * catch-all) are ordinary {@link ObjectSelection}s once built, so they join the same queue as
     * plain object fields; the polymorphic selection itself is recorded separately, to render its
     * sealed interface and dispatching decode method once.
     */
    private static void enqueueNestedSelections(
            FieldShape shape, Deque<ObjectSelection> queue, List<PolymorphicSelection> polymorphicSelections) {
        switch (shape) {
            case FieldShape.ObjectField object -> queue.addLast(object.selection());
            case FieldShape.PolymorphicField polymorphic -> {
                polymorphicSelections.add(polymorphic.selection());
                for (PolymorphicBranch branch : polymorphic.selection().branches()) {
                    queue.addLast(branch.selection());
                }
                queue.addLast(polymorphic.selection().unrecognizedBranch());
            }
            case FieldShape.ListField list -> enqueueNestedSelections(list.elementShape(), queue, polymorphicSelections);
            case FieldShape.ScalarField ignored -> {}
            case FieldShape.EnumField ignored -> {}
        }
    }

    /**
     * Every distinct custom scalar reachable from either the output selection tree or the
     * variable/input-object tree, in first-encountered order. A nested object field or
     * polymorphic branch's own scalar fields are found through its own entry in {@code
     * objectSelections} (already flattened breadth-first), so only list wrapping needs unwrapping
     * here; likewise a nested input object's fields are found through {@code
     * variables.inputObjectTypes()} directly, not by recursing into {@link
     * InputShape.InputObjectShape}.
     */
    private static List<CustomScalarType> collectCustomScalars(
            List<ObjectSelection> objectSelections, VariableAnalyzer.Result variables) {
        Map<String, CustomScalarType> byGraphqlName = new LinkedHashMap<>();
        for (ObjectSelection type : objectSelections) {
            for (FieldSelection field : type.fields()) {
                collectFromFieldShape(field.shape(), byGraphqlName);
            }
        }
        for (InputFieldDefinition variable : variables.variables()) {
            collectFromInputShape(variable.shape(), byGraphqlName);
        }
        for (InputObjectType inputObjectType : variables.inputObjectTypes()) {
            for (InputFieldDefinition field : inputObjectType.fields()) {
                collectFromInputShape(field.shape(), byGraphqlName);
            }
        }
        return List.copyOf(byGraphqlName.values());
    }

    private static void collectFromFieldShape(FieldShape shape, Map<String, CustomScalarType> byGraphqlName) {
        switch (shape) {
            case FieldShape.ScalarField scalar -> {
                if (scalar.scalar() instanceof CustomScalarType custom) {
                    byGraphqlName.putIfAbsent(custom.graphqlName(), custom);
                }
            }
            case FieldShape.ListField list -> collectFromFieldShape(list.elementShape(), byGraphqlName);
            case FieldShape.ObjectField ignored -> {}
            case FieldShape.PolymorphicField ignored -> {}
            case FieldShape.EnumField ignored -> {}
        }
    }

    private static void collectFromInputShape(InputShape shape, Map<String, CustomScalarType> byGraphqlName) {
        switch (shape) {
            case InputShape.ScalarShape scalar -> {
                if (scalar.scalar() instanceof CustomScalarType custom) {
                    byGraphqlName.putIfAbsent(custom.graphqlName(), custom);
                }
            }
            case InputShape.ListShape list -> collectFromInputShape(list.elementShape(), byGraphqlName);
            case InputShape.EnumShape ignored -> {}
            case InputShape.InputObjectShape ignored -> {}
        }
    }

    private static void appendScalarCodecFields(StringBuilder out, List<CustomScalarType> customScalars) {
        for (CustomScalarType scalar : customScalars) {
            out.append("    private static final ScalarCodec<")
                    .append(scalar.javaTypeName())
                    .append("> ")
                    .append(scalar.codecFieldName())
                    .append(" = new ")
                    .append(scalar.codecClassName())
                    .append("();\n\n");
        }
    }

    private static Map<String, String> implementsInterfaceByTypeName(List<PolymorphicSelection> polymorphicSelections) {
        Map<String, String> result = new LinkedHashMap<>();
        for (PolymorphicSelection polymorphic : polymorphicSelections) {
            for (PolymorphicBranch branch : polymorphic.branches()) {
                result.put(branch.selection().javaTypeName(), polymorphic.javaTypeName());
            }
            result.put(polymorphic.unrecognizedBranch().javaTypeName(), polymorphic.javaTypeName());
        }
        return result;
    }

    private static void appendDecodeMethod(StringBuilder out, ObjectSelection type) {
        out.append("    private static ")
                .append(type.javaTypeName())
                .append(" decode")
                .append(type.javaTypeName())
                .append("(Map<String, Object> map, DecodingPolicy policy) {\n");

        List<String> constructorArgs = new ArrayList<>();
        for (FieldSelection field : type.fields()) {
            String valueVar = JavaIdentifiers.fieldIdentifier(field.responseName()) + "Value";
            out.append("        Object ")
                    .append(valueVar)
                    .append(" = map.get(")
                    .append(JavaLiterals.quote(field.responseName()))
                    .append(");\n");
            constructorArgs.add(decodeExpression(field.shape(), valueVar, 0));
        }

        out.append("        return new ").append(type.javaTypeName()).append('(');
        out.append(constructorArgs.isEmpty() ? "" : "\n");
        for (int i = 0; i < constructorArgs.size(); i++) {
            out.append("            ").append(constructorArgs.get(i));
            out.append(i < constructorArgs.size() - 1 ? ",\n" : "\n");
        }
        out.append(constructorArgs.isEmpty() ? "" : "        ");
        out.append(");\n");
        out.append("    }\n\n");
    }

    private static void appendPolymorphicDecodeMethod(StringBuilder out, PolymorphicSelection polymorphic) {
        out.append("    private static ")
                .append(polymorphic.javaTypeName())
                .append(" decode")
                .append(polymorphic.javaTypeName())
                .append("(Map<String, Object> map, DecodingPolicy policy) {\n");
        out.append("        String typename = GraphQlDecoding.asString(map.get(")
                .append(JavaLiterals.quote(polymorphic.discriminatorResponseKey()))
                .append("));\n");
        out.append("        return switch (typename) {\n");
        for (PolymorphicBranch branch : polymorphic.branches()) {
            out.append("            case ")
                    .append(JavaLiterals.quote(branch.graphqlTypeName()))
                    .append(" -> decode")
                    .append(branch.selection().javaTypeName())
                    .append("(map, policy);\n");
        }
        out.append("            default -> {\n");
        out.append("                if (policy == DecodingPolicy.STRICT) {\n");
        out.append("                    throw new IllegalArgumentException(")
                .append(JavaLiterals.quote("Expected a known concrete type for '" + polymorphic.javaTypeName() + "', got '"))
                .append(" + typename + ")
                .append(JavaLiterals.quote("'."))
                .append(");\n");
        out.append("                }\n");
        out.append("                yield decode")
                .append(polymorphic.unrecognizedBranch().javaTypeName())
                .append("(map, policy);\n");
        out.append("            }\n");
        out.append("        };\n");
        out.append("    }\n\n");
    }

    private static String decodeExpression(FieldShape shape, String valueVar, int depth) {
        String nonNullExpression = nonNullDecodeExpression(shape, valueVar, depth);
        return shape.nullable() ? (valueVar + " == null ? null : " + nonNullExpression) : nonNullExpression;
    }

    /**
     * The decode expression for {@code valueVar} assuming it is already known non-null: used only
     * for a field whose shape is itself non-null. A list element's own decode expression still
     * goes through {@link #decodeExpression}, not this method, since {@link
     * dev.glisseo.izar.operation.GraphQlDecoding#decodeList} passes every element through
     * (including {@code null} ones) and relies on the generated element lambda to null-check when
     * the schema permits a {@code null} element.
     */
    private static String nonNullDecodeExpression(FieldShape shape, String valueVar, int depth) {
        return switch (shape) {
            case FieldShape.ScalarField scalar -> scalarDecodeExpression(scalar.scalar(), valueVar);
            case FieldShape.EnumField enumField -> enumDecodeExpression(enumField, valueVar);
            case FieldShape.ObjectField object ->
                    "decode"
                            + object.selection().javaTypeName()
                            + "(GraphQlDecoding.asMap("
                            + valueVar
                            + "), policy)";
            case FieldShape.PolymorphicField polymorphic ->
                    "decode"
                            + polymorphic.selection().javaTypeName()
                            + "(GraphQlDecoding.asMap("
                            + valueVar
                            + "), policy)";
            case FieldShape.ListField list -> {
                String elementVar = "element" + depth;
                yield "GraphQlDecoding.decodeList("
                        + valueVar
                        + ", ("
                        + elementVar
                        + ") -> "
                        + decodeExpression(list.elementShape(), elementVar, depth + 1)
                        + ")";
            }
        };
    }

    private static String scalarDecodeExpression(ScalarType scalar, String valueVar) {
        return switch (scalar) {
            case BuiltinScalar builtin -> "GraphQlDecoding." + builtin.decodeMethodName() + "(" + valueVar + ")";
            case CustomScalarType custom ->
                    "GraphQlDecoding.decodeScalar("
                            + valueVar
                            + ", "
                            + custom.codecFieldName()
                            + ", "
                            + JavaLiterals.quote(custom.graphqlName())
                            + ")";
        };
    }

    private static String enumDecodeExpression(FieldShape.EnumField enumField, String valueVar) {
        String javaTypeName = enumField.enumType().javaTypeName();
        return "GraphQlDecoding.decodeEnum("
                + valueVar
                + ", "
                + javaTypeName
                + ".Known.class, known -> known, "
                + javaTypeName
                + ".Unrecognized::new, "
                + JavaLiterals.quote(enumField.enumType().graphqlName())
                + ", policy)";
    }

    private static void appendRecord(StringBuilder out, ObjectSelection type, @Nullable String polymorphicInterface) {
        out.append("    public record ").append(type.javaTypeName()).append('(');
        List<FieldSelection> fields = type.fields();
        out.append(fields.isEmpty() ? "" : "\n");
        for (int i = 0; i < fields.size(); i++) {
            out.append("            ").append(fieldTypeAndName(fields.get(i)));
            out.append(i < fields.size() - 1 ? ",\n" : "\n");
        }
        out.append(fields.isEmpty() ? "" : "    ");
        out.append(')');
        List<String> interfaces = new ArrayList<>(type.implementsFragments());
        if (polymorphicInterface != null) {
            interfaces.add(polymorphicInterface);
        }
        if (!interfaces.isEmpty()) {
            out.append(" implements ").append(String.join(", ", interfaces));
        }
        out.append(" {}\n\n");
    }

    private static void appendPolymorphicInterface(StringBuilder out, PolymorphicSelection polymorphic) {
        List<String> permitted = new ArrayList<>();
        for (PolymorphicBranch branch : polymorphic.branches()) {
            permitted.add(branch.selection().javaTypeName());
        }
        permitted.add(polymorphic.unrecognizedBranch().javaTypeName());

        out.append("    public sealed interface ")
                .append(polymorphic.javaTypeName())
                .append(" permits ")
                .append(String.join(", ", permitted))
                .append(" {}\n\n");
    }

    private static void appendOutputEnumType(StringBuilder out, OutputEnumType type) {
        out.append("    public sealed interface ").append(type.javaTypeName()).append(" {\n\n");
        out.append("        enum Known implements ").append(type.javaTypeName()).append(" {\n");
        List<String> values = type.values();
        for (int i = 0; i < values.size(); i++) {
            out.append("            ").append(values.get(i));
            out.append(i < values.size() - 1 ? ",\n" : "\n");
        }
        out.append("        }\n\n");
        out.append("        record Unrecognized(String rawValue) implements ").append(type.javaTypeName()).append(" {}\n");
        out.append("    }\n\n");
    }

    /** A field's rendered type and Java identifier, e.g. {@code "@Nullable String name"}. */
    private static String fieldTypeAndName(FieldSelection field) {
        return JavaIdentifiers.nullableTypeReference(javaTypeNameFor(field.shape()), field.shape().nullable())
                + ' '
                + JavaIdentifiers.fieldIdentifier(field.responseName());
    }

    private static String javaTypeNameFor(FieldShape shape) {
        return switch (shape) {
            case FieldShape.ScalarField scalar -> scalar.scalar().javaTypeName();
            case FieldShape.EnumField enumField -> enumField.enumType().javaTypeName();
            case FieldShape.ObjectField object -> object.selection().javaTypeName();
            case FieldShape.PolymorphicField polymorphic -> polymorphic.selection().javaTypeName();
            case FieldShape.ListField list -> "List<" + nullablePrefixedTypeName(list.elementShape()) + ">";
        };
    }

    private static String nullablePrefixedTypeName(FieldShape shape) {
        return JavaIdentifiers.nullableTypeReference(javaTypeNameFor(shape), shape.nullable());
    }
}
